package com.inspien.eai.common.lock;

/**
 * 획득한 락 — 살아 있는 동안만 소유가 보장된다.
 *
 * <p>{@link AutoCloseable} 인 것은 편의가 아니라 <b>계약</b>이다. 락을 놓는 코드를
 * {@code finally} 에 손으로 쓰게 두면 실패 경로 하나에서 빠지고, 그 빠짐은
 * <b>TTL 이 만료될 때까지 배치가 멈추는</b> 증상으로 한참 뒤에 나타난다.
 * {@code try-with-resources} 로 강제하면 어느 경로로 빠져나가도 반납이 지나간다.
 *
 * <h2>"소유가 보장된다" 는 말의 한계</h2>
 * 락에는 TTL 이 있다. 프로세스가 죽어도 영원히 잠기지 않게 하려면 TTL 이 있어야 하고,
 * TTL 이 있으면 <b>수행이 TTL 을 넘기는 순간 소유권이 조용히 사라진다.</b>
 * 그 상태에서 다른 실행이 락을 새로 잡을 수 있으므로, {@link #close()} 는
 * "내가 넣은 값이 아직 거기 있는가" 를 확인한 뒤에만 지워야 한다 —
 * 확인 없이 지우면 <b>남의 락을 풀어 주는</b> 셈이 된다.
 */
public interface LockHandle extends AutoCloseable {

    /** 이 핸들이 쥐고 있는 락 키 */
    String key();

    /**
     * 락을 놓는다.
     *
     * <p>구현은 <b>내가 넣은 토큰이 아직 남아 있을 때만</b> 삭제해야 한다.
     * 예외를 던지지 않는다 — 반납은 이미 본 작업이 끝난 뒤에 불리므로,
     * 여기서 던지면 정상 결과나 원래의 실패 원인을 덮어 버린다.
     * 다만 소유권을 잃은 사실은 <b>반드시 기록한다.</b> 그것은 수행 시간이 TTL 을
     * 넘겼다는 신호이고, 다음 주기와 겹쳐 돌았을 가능성을 뜻한다.
     */
    @Override
    void close();
}
